function escapeHtml(text) {
  return text.replace(/[&<>"']/g, (char) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;"
  })[char]);
}

function escapeRegExp(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function applyStudyRuby(text) {
  const readings = new Map([
    ...Object.entries(rubyGlossary),
    ...people.map((person) => [person[0], person[1]])
  ]);
  const words = [...readings.keys()]
    .filter((word) => text.includes(word))
    .sort((a, b) => b.length - a.length);
  const escaped = escapeHtml(text);
  if (!words.length) return escaped;
  const pattern = new RegExp(words.map(escapeRegExp).join("|"), "g");
  return escaped.replace(pattern, (word) => `<ruby>${escapeHtml(word)}<rt>${readings.get(word)}</rt></ruby>`);
}

function enrichDetailLinks(text) {
  const peopleItems = [...new Set(people.map((person) => person[0]))]
    .filter((name) => text.includes(name))
    .map((name) => ({ name, type: "person" }));
  const actionItems = Object.keys(actionCards)
    .filter((name) => {
      if (name === "元") return /元が大軍|元の襲来|元寇/.test(text);
      return text.includes(name);
    })
    .map((name) => ({ name, type: "action" }));
  const items = [...peopleItems, ...actionItems]
    .sort((a, b) => b.name.length - a.name.length);
  if (!items.length) return applyStudyRuby(text);
  const itemMap = new Map(items.map((item) => [item.name, item.type]));
  const pattern = new RegExp(items.map((item) => escapeRegExp(item.name)).join("|"), "g");
  const used = new Set();
  let cursor = 0;
  let html = "";
  for (const match of text.matchAll(pattern)) {
    const name = match[0];
    const index = match.index;
    html += applyStudyRuby(text.slice(cursor, index));
    if (used.has(name)) {
      html += applyStudyRuby(name);
    } else {
      used.add(name);
      const label = name === "元" ? ruby("元", "げん") : applyStudyRuby(name);
      const attrName = escapeHtml(name);
      if (itemMap.get(name) === "action") {
        html += `<button class="action-inline" type="button" data-action-name="${attrName}"><strong>${label}</strong></button>`;
      } else {
        html += `<button class="person-inline" type="button" data-person-name="${attrName}"><strong>${label}</strong></button>`;
      }
    }
    cursor = index + name.length;
  }
  html += applyStudyRuby(text.slice(cursor));
  return html;
}

